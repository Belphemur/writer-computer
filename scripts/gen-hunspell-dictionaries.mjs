#!/usr/bin/env node
// Generates apps/desktop/shared/hunspell-dictionaries.json: the catalog of Hunspell dictionaries
// the spellcheck feature can install (ADR 2026-11-18 "check spelling and grammar locally"), taken
// from the wooorm/dictionaries repository at ONE pinned commit.
//
//   node scripts/gen-hunspell-dictionaries.mjs <commit-sha>
//
// For every dictionary folder it downloads `index.aff` and `index.dic` once to record their sha256
// and size, and reads the licence from the folder's package.json. The app never trusts a branch:
// every URL in the catalog names the commit, and an install refuses a file whose sha256 differs.
// Run it again with a new commit to upgrade the dictionaries on purpose; the diff of the JSON is
// the review.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const commit = process.argv[2];
if (!/^[0-9a-f]{40}$/.test(commit ?? "")) {
  console.error("usage: node scripts/gen-hunspell-dictionaries.mjs <40-hex commit sha>");
  process.exit(2);
}
const repo = "wooorm/dictionaries";
const base = `https://raw.githubusercontent.com/${repo}/${commit}/dictionaries/`;
const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../apps/desktop/shared/hunspell-dictionaries.json",
);

async function get(url, asJson = false) {
  const r = await fetch(url, { headers: { "user-agent": "writer-catalog-generator" } });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return asJson ? r.json() : Buffer.from(await r.arrayBuffer());
}

const tree = await get(
  `https://api.github.com/repos/${repo}/git/trees/${commit}?recursive=1`,
  true,
);
if (tree.truncated) throw new Error("the repository tree is truncated");
const ids = [
  ...new Set(
    tree.tree.map((e) => /^dictionaries\/([^/]+)\/index\.dic$/.exec(e.path)?.[1]).filter(Boolean),
  ),
].sort();

const names = new Intl.DisplayNames(["en"], { type: "language", languageDisplay: "standard" });
const normalise = (id) =>
  id
    .split("-")
    .map((p, i) => {
      if (i === 0 || p.length >= 5) return p.toLowerCase(); // language, variant
      return p.length === 4 ? p[0].toUpperCase() + p.slice(1).toLowerCase() : p.toUpperCase(); // script, region
    })
    .join("-");

async function entry(id) {
  const tag = normalise(id);
  if (tag !== id) throw new Error(`${id} is not a normalised language tag`);
  const file = async (name) => {
    const bytes = await get(`${base}${id}/${name}`);
    return {
      url: `${base}${id}/${name}`,
      sha256: createHash("sha256").update(bytes).digest("hex"),
      bytes: bytes.length,
    };
  };
  const [aff, dic, pkg] = await Promise.all([
    file("index.aff"),
    file("index.dic"),
    get(`${base}${id}/package.json`, true),
  ]);
  let name;
  try {
    name = names.of(id);
  } catch {
    name = undefined;
  }
  return { id, name: name && name !== id ? name : id, license: pkg.license, aff, dic };
}

const dictionaries = [];
for (let i = 0; i < ids.length; i += 6) {
  dictionaries.push(...(await Promise.all(ids.slice(i, i + 6).map(entry))));
  console.error(`${Math.min(i + 6, ids.length)}/${ids.length}`);
}

const catalog = {
  $comment:
    "GENERATED by scripts/gen-hunspell-dictionaries.mjs. Do not edit; see SPECs/spellcheck-spec.md (Dictionaries).",
  source: { repository: `https://github.com/${repo}`, commit, base },
  dictionaries,
};
writeFileSync(out, `${JSON.stringify(catalog, null, 2)}\n`);
console.error(`wrote ${dictionaries.length} dictionaries to ${out}`);
