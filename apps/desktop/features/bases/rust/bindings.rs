//! The Bases typed IPC surface: the one list of its commands (the plugin's invoke handler and the
//! TypeScript bindings both come from it) and the exporter of `web/bindings.ts`. Same shape and
//! exporter settings as `features/agent/rust/bindings.rs` (SPECs/builtin-plugins-spec.md 6.4).
use super::commands;
use tauri::{Runtime, Wry};
use tauri_specta::{collect_commands, Builder};

pub fn builder<R: Runtime>() -> Builder<R> {
    Builder::<R>::new()
        .plugin_name("bases")
        .dangerously_cast_bigints_to_number()
        .disable_serde_phases()
        .commands(collect_commands![
            commands::base_list::<Wry>,
            commands::base_read::<Wry>,
            commands::base_parse_text,
            commands::base_functions,
            commands::base_query::<Wry>,
            commands::base_query_text::<Wry>,
            commands::base_eval::<Wry>,
            commands::note_properties::<Wry>,
            commands::note_property_set::<Wry>,
            commands::note_property_remove::<Wry>,
        ])
}

#[cfg(test)]
mod tests {
    use super::*;
    use specta_typescript::Typescript;
    use std::path::PathBuf;

    const HEADER: &str = "// GENERATED by `WRITER_UPDATE_BINDINGS=1 cargo test bindings` from features/bases/rust. Do not edit.\n// Only `ipc.ts` imports this file (and the tests that read it).\n/* eslint-disable */\n";

    fn bindings_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../features/bases/web/bindings.ts")
    }

    fn render() -> String {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("bindings.ts");
        builder::<Wry>()
            .export(Typescript::default().header(HEADER), &out)
            .expect("bindings export");
        std::fs::read_to_string(out).unwrap()
    }

    /// `WRITER_UPDATE_BINDINGS=1 cargo test bindings` rewrites the file (like the goldens).
    #[test]
    fn the_checked_in_bindings_match_the_commands() {
        let fresh = render();
        let path = bindings_path();
        if std::env::var_os("WRITER_UPDATE_BINDINGS").is_some() {
            std::fs::write(&path, &fresh).unwrap();
            return;
        }
        let checked_in = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            checked_in == fresh,
            "features/bases/web/bindings.ts is stale: run `WRITER_UPDATE_BINDINGS=1 cargo test bindings` and commit it"
        );
    }
}
