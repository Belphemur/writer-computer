const ICONS: ReadonlyMap<string, IconData> = new Map(
  ICON_ROWS.flatMap(([ids, data]) => ids.map((id) => [id, data] as const)),
);

/** Every id the host can draw (custom `addIcon` icons are separate, see functions.ts). */
export const BUILTIN_ICON_IDS: readonly string[] = [...ICONS.keys()];

const kebab = (attr: string): string => attr.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** The built-in icon for `name` (a `lucide-` prefix is accepted) as inner SVG markup, or null. */
export function builtinIconMarkup(name: string): string | null {
  const data = ICONS.get(name.replace(/^lucide-/, ""));
  if (!data) return null;
  return data
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${kebab(k)}="${v}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}
