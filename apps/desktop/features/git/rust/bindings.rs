//! The git feature's typed IPC surface: the one list of its commands (the plugin's invoke handler
//! and the TypeScript bindings both come from it) and the exporter of `web/bindings.ts`.
use super::commands;
use tauri::{Runtime, Wry};
use tauri_specta::{collect_commands, Builder};

pub fn builder<R: Runtime>() -> Builder<R> {
    Builder::<R>::new()
        .plugin_name("git")
        .dangerously_cast_bigints_to_number()
        .disable_serde_phases()
        .commands(collect_commands![
            commands::git_status::<Wry>,
            commands::git_setup::<Wry>,
            commands::git_commit_now::<Wry>,
            commands::git_set_paused::<Wry>,
            commands::git_stop::<Wry>,
            commands::git_history::<Wry>,
            commands::git_deleted::<Wry>,
            commands::git_version_diff::<Wry>,
            commands::git_version_text::<Wry>,
            commands::git_restore::<Wry>,
            commands::git_turn_commit::<Wry>,
            commands::git_sync_now::<Wry>,
            commands::git_set_sync_paused::<Wry>,
            commands::git_remote_set::<Wry>,
            commands::git_remote_remove::<Wry>,
            commands::git_tools::<Wry>,
            commands::git_install_git::<Wry>,
            commands::git_sign_in_github::<Wry>,
            commands::git_set_credentials::<Wry>,
            commands::git_plugin_decision::<Wry>,
            commands::git_dismiss_notices::<Wry>,
            commands::git_merge_text::<Wry>,
            commands::git_conflict_open::<Wry>,
            commands::git_conflict_save::<Wry>,
            commands::git_conflict_take::<Wry>,
            commands::git_conflict_record::<Wry>,
        ])
}

#[cfg(test)]
mod tests {
    use super::*;
    use specta_typescript::Typescript;
    use std::path::PathBuf;

    const HEADER: &str = "// GENERATED by `WRITER_UPDATE_BINDINGS=1 cargo test bindings` from features/git/rust. Do not edit.\n// Only `ipc.ts` imports this file (and the tests that read it).\n/* eslint-disable */\n";

    fn bindings_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../features/git/web/bindings.ts")
    }

    fn render() -> String {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("bindings.ts");
        builder::<Wry>()
            .export(Typescript::default().header(HEADER), &out)
            .expect("bindings export");
        std::fs::read_to_string(out).unwrap()
    }

    /// `WRITER_UPDATE_BINDINGS=1 cargo test bindings` rewrites the file (like the goldens).
    #[test]
    fn the_checked_in_bindings_match_the_commands() {
        let fresh = render();
        let path = bindings_path();
        if std::env::var_os("WRITER_UPDATE_BINDINGS").is_some() {
            std::fs::write(&path, &fresh).unwrap();
            return;
        }
        let checked_in = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            checked_in == fresh,
            "features/git/web/bindings.ts is stale: run `WRITER_UPDATE_BINDINGS=1 cargo test bindings` and commit it"
        );
    }
}
