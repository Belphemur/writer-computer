//! The agent's typed IPC surface: the one list of its commands (the plugin's invoke handler and
//! the TypeScript bindings both come from it) and the exporter of `web/bindings.ts`.
//!
//! `collect_commands!` needs the concrete runtime in each `::<Wry>`: it cannot see the generic
//! parameter of an enclosing function, and the metadata it collects does not depend on the runtime
//! (the handler itself stays generic, so the same list serves the mock runtime in tests).
use super::commands::{chats, projects, session, skills};
use crate::agent::events::AgentEventEnvelope;
use tauri::{Runtime, Wry};
use tauri_specta::{collect_commands, Builder};

/// The builder: commands, the types the event payload needs, and the exporter settings (decided
/// once for every feature, SPECs/builtin-plugins-spec.md section 6.4): `u64` fields are counters,
/// durations and timestamps far below 2^53, so they are `number`; serde phases are unified.
pub fn builder<R: Runtime>() -> Builder<R> {
    Builder::<R>::new()
        .plugin_name("agent")
        .dangerously_cast_bigints_to_number()
        .disable_serde_phases()
        // The payload of the `agent:event` event (emitted with a plain `emit_to`, see the module
        // docs of `mod.rs`): exported as a type, listened to through `ipc.ts`.
        .typ::<AgentEventEnvelope>()
        .commands(collect_commands![
            session::agent_detect_binary::<Wry>,
            session::agent_start::<Wry>,
            session::agent_send::<Wry>,
            session::agent_cancel::<Wry>,
            session::agent_permission::<Wry>,
            session::agent_set_permission_mode::<Wry>,
            session::agent_set_model::<Wry>,
            session::agent_close::<Wry>,
            session::agent_resume::<Wry>,
            session::agent_snapshot::<Wry>,
            session::agent_turn_changes::<Wry>,
            session::agent_revert_changes::<Wry>,
            skills::agent_list_skills::<Wry>,
            chats::agent_list_chats::<Wry>,
            chats::agent_load_chat::<Wry>,
            chats::agent_save_chat::<Wry>,
            chats::agent_chat_action::<Wry>,
            chats::agent_auto_title::<Wry>,
            chats::agent_regenerate_title::<Wry>,
            chats::agent_chat_replay::<Wry>,
            chats::agent_save_chat_image::<Wry>,
            chats::agent_import_chat_image_file::<Wry>,
            chats::agent_permission_rules::<Wry>,
            chats::agent_remove_permission_rule::<Wry>,
            projects::agent_list_projects::<Wry>,
            projects::agent_read_project::<Wry>,
            projects::agent_create_project::<Wry>,
            projects::agent_make_project::<Wry>,
            projects::agent_update_project::<Wry>,
            projects::agent_archive_project::<Wry>,
            projects::agent_inspect_folder::<Wry>,
            projects::agent_project_manifest::<Wry>,
        ])
}

#[cfg(test)]
mod tests {
    use super::*;
    use specta_typescript::Typescript;
    use std::path::PathBuf;

    const HEADER: &str = "// GENERATED by `WRITER_UPDATE_BINDINGS=1 cargo test bindings` from features/agent/rust. Do not edit.\n// Only `ipc.ts` imports this file (and the tests that read it).\n/* eslint-disable */\n";

    fn bindings_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../features/agent/web/bindings.ts")
    }

    fn render() -> String {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("bindings.ts");
        builder::<Wry>()
            .export(Typescript::default().header(HEADER), &out)
            .expect("bindings export");
        std::fs::read_to_string(out).unwrap()
    }

    /// `WRITER_UPDATE_BINDINGS=1 cargo test bindings` rewrites the file (like the goldens).
    #[test]
    fn the_checked_in_bindings_match_the_commands() {
        let fresh = render();
        let path = bindings_path();
        if std::env::var_os("WRITER_UPDATE_BINDINGS").is_some() {
            std::fs::write(&path, &fresh).unwrap();
            return;
        }
        let checked_in = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            checked_in == fresh,
            "features/agent/web/bindings.ts is stale: run `WRITER_UPDATE_BINDINGS=1 cargo test bindings` and commit it"
        );
    }
}
